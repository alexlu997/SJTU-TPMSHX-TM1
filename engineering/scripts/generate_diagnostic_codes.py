"""Generate the public C++ diagnostic identifiers from the Python package catalog."""
import argparse
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
CATALOG = ROOT / 'python/model_configs/diagnostic_codes_v1.json'
HEADER = ROOT / 'native/include/tpmshx/diagnostic_codes.hpp'


def render():
    catalog = json.loads(CATALOG.read_text(encoding='utf-8'))
    codes = catalog['codes']
    identifiers = [f'inline constexpr char {code.replace(".", "_")}[] = "{code}";' for code in sorted(codes)]
    bindings = catalog['native_operations']
    native_ids = []
    for family, member in (('flow', 'status'), ('result', 'cause')):
        native_ids.append(f'namespace {family}_{member} {{')
        for number, code in bindings[family][member].items():
            native_ids.append(f'inline constexpr int {code.replace(".", "_")} = {number};')
        native_ids.append('}')
    return '\n'.join([
        '// Generated by engineering/scripts/generate_diagnostic_codes.py.',
        '#pragma once', '', 'namespace tpmshx::diagnostic {', *identifiers,
        '', *native_ids, '}  // namespace tpmshx::diagnostic', '',
    ])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Compare the header without writing files.')
    args = parser.parse_args()
    source = render()
    if args.check:
        if HEADER.read_text(encoding='utf-8') != source:
            parser.exit(1, 'Regenerate native/include/tpmshx/diagnostic_codes.hpp.\n')
    else:
        HEADER.write_text(source, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
